/*
# Create secure quote request tracking

1. New Tables
- `quote_requests`
- `id` (uuid): Internal request identifier.
- `reference_code` (text): Short, unique tracking reference shown to the requester.
- `status` (text): Current request stage, restricted to the supported workflow values.
- `full_name`, `email`, `phone`, `country`: Contact details supplied by the requester.
- `care_type`, `treatment`, `preferred_city`, `timeline`, `condition_summary`: Care planning details.
- `donor_required`: Whether the requested pathway needs a donor.
- `donor_relationship`, `donor_blood_group`, `donor_age`, `donor_health_notes`: Optional donor information for transplant pathways.
- `created_at`, `updated_at`: Request timestamps.

2. Security
- Row level security is enabled.
- The public browser roles receive no direct table access; requests are created and looked up only through the server-side tracking function.
- The service role receives the minimum SELECT and INSERT privileges needed by that function.

3. Important Notes
- Tracking references are generated by the server and are the only public lookup credential.
- Request status is intentionally controlled outside the public browser flow so users cannot mark their own request as approved or completed.
*/

CREATE TABLE IF NOT EXISTS public.quote_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  reference_code text NOT NULL UNIQUE,
  status text NOT NULL DEFAULT 'submitted' CHECK (status IN ('submitted', 'under_review', 'options_ready', 'coordination', 'completed')),
  full_name text NOT NULL,
  email text NOT NULL,
  phone text NOT NULL,
  country text NOT NULL,
  care_type text NOT NULL CHECK (care_type IN ('allopathic', 'ayush')),
  treatment text NOT NULL,
  preferred_city text,
  timeline text,
  condition_summary text,
  donor_required boolean NOT NULL DEFAULT false,
  donor_relationship text,
  donor_blood_group text,
  donor_age integer,
  donor_health_notes text,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.quote_requests ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public.quote_requests FROM anon, authenticated;
GRANT SELECT, INSERT ON TABLE public.quote_requests TO service_role;

CREATE INDEX IF NOT EXISTS quote_requests_status_idx ON public.quote_requests (status);
CREATE INDEX IF NOT EXISTS quote_requests_created_at_idx ON public.quote_requests (created_at DESC);
